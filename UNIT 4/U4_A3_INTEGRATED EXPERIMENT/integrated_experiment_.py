import numpy as np
import random
import matplotlib.pyplot as plt

# -----------------------------
# Q-Learning - 4x4 Grid World
# -----------------------------

GRID_SIZE = 4
NUM_STATES = 16

# Grid configuration
START_STATE = 0
GOAL_STATE = 15
OBSTACLE_STATE = 5

# Actions
UP = 0
DOWN = 1
LEFT = 2
RIGHT = 3

actions = ["UP", "DOWN", "LEFT", "RIGHT"]

# Q-Learning parameters
alpha = 0.1
gamma = 0.9
epsilon = 0.2

episodes = 100
max_steps = 100

# Initialize Q-table
Q = np.zeros((NUM_STATES, 4))

# Store Q-values at selected episodes
q_episode_1 = None
q_episode_50 = None
q_episode_100 = None

# Store rewards
episode_rewards = []


# -----------------------------
# Find Next State
# -----------------------------
def get_next_state(state, action):

    row = state // GRID_SIZE
    col = state % GRID_SIZE

    new_row = row
    new_col = col

    if action == UP:
        new_row -= 1

    elif action == DOWN:
        new_row += 1

    elif action == LEFT:
        new_col -= 1

    elif action == RIGHT:
        new_col += 1

    # Prevent movement outside the grid
    if new_row < 0 or new_row >= GRID_SIZE:
        return state

    if new_col < 0 or new_col >= GRID_SIZE:
        return state

    return new_row * GRID_SIZE + new_col


# -----------------------------
# Reward Function
# -----------------------------
def get_reward(next_state):

    if next_state == GOAL_STATE:
        return 10

    elif next_state == OBSTACLE_STATE:
        return -5

    else:
        return -1


# -----------------------------
# Q-Learning Training
# -----------------------------
for episode in range(1, episodes + 1):

    state = START_STATE
    total_reward = 0

    for step in range(max_steps):

        # Epsilon-greedy action selection
        if random.random() < epsilon:
            action = random.randint(0, 3)
        else:
            action = np.argmax(Q[state])

        # Find next state
        next_state = get_next_state(state, action)

        # Get reward
        reward = get_reward(next_state)

        # Q-Learning update
        Q[state, action] = Q[state, action] + alpha * (
            reward
            + gamma * np.max(Q[next_state])
            - Q[state, action]
        )

        total_reward += reward

        # Move to next state
        state = next_state

        # Stop when goal is reached
        if state == GOAL_STATE:
            break

    episode_rewards.append(total_reward)

    # Store Q-values
    if episode == 1:
        q_episode_1 = Q.copy()

    elif episode == 50:
        q_episode_50 = Q.copy()

    elif episode == 100:
        q_episode_100 = Q.copy()


# -----------------------------
# Display Q-Values
# -----------------------------
np.set_printoptions(precision=2, suppress=True)

print("=" * 50)
print("Q-VALUES AT EPISODE 1")
print("=" * 50)
print(q_episode_1)

print("\n" + "=" * 50)
print("Q-VALUES AT EPISODE 50")
print("=" * 50)
print(q_episode_50)

print("\n" + "=" * 50)
print("Q-VALUES AT EPISODE 100")
print("=" * 50)
print(q_episode_100)


# -----------------------------
# Final Q-Table
# -----------------------------
print("\n" + "=" * 50)
print("FINAL Q-TABLE")
print("=" * 50)
print(Q)


# -----------------------------
# Display Learned Policy
# -----------------------------
print("\n" + "=" * 50)
print("FINAL LEARNED POLICY")
print("=" * 50)

symbols = {
    UP: "↑",
    DOWN: "↓",
    LEFT: "←",
    RIGHT: "→"
}

for row in range(GRID_SIZE):

    policy_row = []

    for col in range(GRID_SIZE):

        state = row * GRID_SIZE + col

        if state == GOAL_STATE:
            policy_row.append("G")

        elif state == OBSTACLE_STATE:
            policy_row.append("X")

        else:
            best_action = np.argmax(Q[state])
            policy_row.append(symbols[best_action])

    print(" | ".join(policy_row))


# -----------------------------
# Display Grid World
# -----------------------------
print("\n" + "=" * 50)
print("GRID WORLD")
print("=" * 50)

for row in range(GRID_SIZE):

    grid_row = []

    for col in range(GRID_SIZE):

        state = row * GRID_SIZE + col

        if state == START_STATE:
            grid_row.append("S")

        elif state == GOAL_STATE:
            grid_row.append("G")

        elif state == OBSTACLE_STATE:
            grid_row.append("X")

        else:
            grid_row.append(str(state))

    print(" | ".join(grid_row))


# -----------------------------
# Plot Cumulative Reward
# -----------------------------
plt.figure(figsize=(10, 5))

plt.plot(
    range(1, episodes + 1),
    episode_rewards,
    marker="o",
    markersize=3
)

plt.xlabel("Episode")
plt.ylabel("Cumulative Reward")
plt.title("Q-Learning - Cumulative Reward per Episode")
plt.grid(True)

plt.tight_layout()
plt.show()