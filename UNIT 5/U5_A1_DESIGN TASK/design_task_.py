# Q3. AI-BASED FRAUD DETECTION FRAMEWORK
# ============================================================

print("\n========== Q3: AI-BASED FRAUD DETECTION ==========")

transactions = [
    ("T1", "U1", 500, "Chennai"),
    ("T2", "U1", 600, "Chennai"),
    ("T3", "U2", 2000, "Bangalore"),
    ("T4", "U3", 250000, "Foreign"),
    ("T5", "U2", 1500, "Bangalore"),
    ("T6", "U4", 300000, "Foreign")
]

transaction_rdd = sc.parallelize(transactions)

# Remove invalid transactions
clean_transactions = transaction_rdd.filter(
    lambda x: x[2] > 0
)

# Extract transaction features
features_rdd = clean_transactions.map(
    lambda x: (
        x[0],
        {
            "user": x[1],
            "amount": x[2],
            "location": x[3]
        }
    )
)

# Simple anomaly detection
def calculate_risk(record):
    transaction_id, data = record

    risk = 0

    if data["amount"] > 100000:
        risk += 70

    if data["location"] == "Foreign":
        risk += 20

    if data["amount"] > 50000:
        risk += 10

    return transaction_id, risk

risk_rdd = features_rdd.map(calculate_risk)

# Classify transactions
fraud_rdd = risk_rdd.map(
    lambda x: (
        x[0],
        x[1],
        "FRAUD" if x[1] >= 70 else "SAFE"
    )
)

print("Fraud Detection Results:")
for transaction in fraud_rdd.collect():
    print(transaction)


# Intelligent Agents

class AnomalyAgent:
    def analyze(self, risk):
        return risk >= 70


class AlertAgent:
    def alert(self, suspicious):
        if suspicious:
            return "FRAUD ALERT"
        return "NO ALERT"


class LearningAgent:
    def learn(self, feedback):
        print("Learning Agent: Model updated using", feedback)


anomaly_agent = AnomalyAgent()
alert_agent = AlertAgent()
learning_agent = LearningAgent()

for transaction_id, risk, status in fraud_rdd.collect():

    suspicious = anomaly_agent.analyze(risk)
    alert = alert_agent.alert(suspicious)

    print(transaction_id, "->", alert)

learning_agent.learn("Confirmed fraud cases")


