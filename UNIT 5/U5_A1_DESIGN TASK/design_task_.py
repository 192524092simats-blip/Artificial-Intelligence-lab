print("\n========== Q1: HYBRID AI RECOMMENDATION ENGINE ==========")

# Sample user-item-rating data
ratings = [
    ("U1", "I1", 5.0),
    ("U1", "I2", 4.0),
    ("U1", "I3", 2.0),
    ("U2", "I1", 4.0),
    ("U2", "I2", 5.0),
    ("U2", "I4", 4.0),
    ("U3", "I2", 4.0),
    ("U3", "I3", 5.0),
    ("U3", "I4", 5.0)
]

ratings_rdd = sc.parallelize(ratings)

# Map user-item interactions
user_item_rdd = ratings_rdd.map(
    lambda x: ((x[0], x[1]), x[2])
)

# Filter valid ratings
clean_rdd = user_item_rdd.filter(
    lambda x: x[1] > 0
)

# Calculate average rating for each item
item_ratings = ratings_rdd.map(
    lambda x: (x[1], x[2])
)

item_average = item_ratings.groupByKey().mapValues(
    lambda values: sum(values) / len(values)
)

# Content-based recommendation
content_features = {
    "I1": {"action", "adventure"},
    "I2": {"action", "fantasy"},
    "I3": {"fantasy", "animation"},
    "I4": {"action", "fantasy"}
}

def content_score(item):
    preferred = {"action", "fantasy"}
    features = content_features.get(item, set())
    return len(preferred.intersection(features))

content_scores = sc.parallelize(
    list(content_features.keys())
).map(
    lambda item: (item, content_score(item))
)

# Collaborative filtering style score
collaborative_scores = item_average.mapValues(
    lambda x: x / 5.0
)

# Hybrid score
hybrid_scores = content_scores.join(
    collaborative_scores
).mapValues(
    lambda x: 0.5 * x[0] + 0.5 * x[1]
)

recommendations = hybrid_scores.sortBy(
    lambda x: x[1],
    ascending=False
)

print("Hybrid Recommendations:")
for item, score in recommendations.collect():
    print(item, "Score:", round(score, 3))


