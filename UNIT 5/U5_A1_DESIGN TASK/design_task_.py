print("\n========== Q2: SMART DISASTER DETECTION ==========")

# Sample multi-source data
sensor_data = [
    ("Chennai", "water", 90),
    ("Chennai", "rain", 85),
    ("Chennai", "water", 95),
    ("CityA", "water", 30),
    ("CityB", "water", 40)
]

social_data = [
    ("Chennai", "flood"),
    ("Chennai", "flood"),
    ("CityA", "normal"),
    ("CityB", "normal")
]

satellite_data = [
    ("Chennai", "flooded_area", 1),
    ("CityA", "flooded_area", 0),
    ("CityB", "flooded_area", 0)
]

sensor_rdd = sc.parallelize(sensor_data)
social_rdd = sc.parallelize(social_data)
satellite_rdd = sc.parallelize(satellite_data)

# Sensor processing
clean_sensor = sensor_rdd.filter(
    lambda x: x[2] >= 0
)

water_rdd = clean_sensor.filter(
    lambda x: x[1] == "water"
).map(
    lambda x: (x[0], x[2])
)

water_average = water_rdd.groupByKey().mapValues(
    lambda values: sum(values) / len(values)
)

# Social media processing
social_count = social_rdd.filter(
    lambda x: x[1] == "flood"
).map(
    lambda x: (x[0], 1)
).reduceByKey(
    lambda a, b: a + b
)

# Satellite processing
satellite_rdd = satellite_rdd.map(
    lambda x: (x[0], x[2])
)

# Data fusion
fusion = water_average.join(
    satellite_rdd
).join(
    social_count
)

# Disaster detection
def detect_disaster(data):
    water_value = data[0][0]
    satellite_flag = data[0][1]
    social_reports = data[1]

    if water_value > 80 and satellite_flag == 1 and social_reports >= 2:
        return "HIGH FLOOD RISK"
    elif water_value > 70:
        return "MEDIUM FLOOD RISK"
    else:
        return "LOW RISK"

disaster_result = fusion.mapValues(detect_disaster)

print("Disaster Detection Results:")
for location, result in disaster_result.collect():
    print(location, ":", result)


# Intelligent Agents

class DetectionAgent:
    def detect(self, result):
        return result


class FusionAgent:
    def confirm(self, result):
        return result == "HIGH FLOOD RISK"


class ResponseAgent:
    def response(self, confirmed):
        if confirmed:
            return "SEND EARLY WARNING"
        return "CONTINUE MONITORING"


detection_agent = DetectionAgent()
fusion_agent = FusionAgent()
response_agent = ResponseAgent()

for location, result in disaster_result.collect():
    detected = detection_agent.detect(result)
    confirmed = fusion_agent.confirm(detected)
    action = response_agent.response(confirmed)

    print(location, "->", action)


